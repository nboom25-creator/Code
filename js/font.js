const FONT_BLACK = "#181818";
const FONT_WHITE = "#f8f8f8";

/* Draw a single line of text. Returns the x cursor after the text. */
function drawText(ctx, text, x, y, color = FONT_BLACK, scale = 1, tracking = 1) {
  let cx = x;
  for (const ch of String(text)) {
    if (ch === "\n") continue;
    const g = FONT[ch] || FONT["?"];
    ctx.fillStyle = color;
    for (let r = 0; r < GLYPH_H; r++) {
      const row = g[r];
      for (let c = 0; c < GLYPH_W; c++) {
        if (row[c] === "#") ctx.fillRect(cx + c * scale, y + r * scale, scale, scale);
      }
    }
    cx += (GLYPH_W + tracking) * scale;
  }
  return cx;
}

/* Multi-line helper with \n support. */
function drawTextLines(ctx, text, x, y, color = FONT_BLACK, scale = 1, tracking = 1, lineGap = 3) {
  const lines = String(text).split("\n");
  lines.forEach((ln, i) => drawText(ctx, ln, x, y + i * (GLYPH_H + lineGap) * scale, color, scale, tracking));
}

function textWidth(text, scale = 1, tracking = 1) {
  return String(text).length * (GLYPH_W + tracking) * scale - tracking * scale;
}

/* Solid right-pointing selector triangle (the menu cursor). */
function drawArrow(ctx, x, y, color = FONT_BLACK, scale = 1) {
  const tri = ["#....", "##...", "###..", "####.", "###..", "##...", "#...."];
  ctx.fillStyle = color;
  for (let r = 0; r < tri.length; r++)
    for (let c = 0; c < 5; c++)
      if (tri[r][c] === "#") ctx.fillRect(x + c * scale, y + r * scale, scale, scale);
}
