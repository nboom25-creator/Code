/* ============================================================
   sprites.js — tiny pixel-art renderer + sprite data.
   Sprites are arrays of strings; each char maps to a color via
   a shared palette. Spaces / "." are transparent.
   ============================================================ */

const PAL = {
  ".": null, " ": null,
  K: "#202020", // outline / black
  W: "#ffffff",
  S: "#9a9a9a", s: "#5a5a5a", // grays
  R: "#e0392b", r: "#a02018", // reds
  O: "#f08030", o: "#c25a12", // oranges
  Y: "#f8d030", y: "#d8a800", // yellows
  G: "#58c850", g: "#3a8a38", // greens
  B: "#5890f0", b: "#2858b0", // blues
  P: "#9858d8", p: "#f0a0c0", // purple / pink
  N: "#d8b070", n: "#9a6a30", // tan / brown
  C: "#f0e0b0", c: "#d8c088", // cream
  T: "#48c0b0", // teal
  L: "#a0e8f0", // light blue (water sheen)
  E: "#f87858", // light orange (belly)
};

function drawGrid(ctx, grid, x, y, scale, pal = PAL) {
  for (let r = 0; r < grid.length; r++) {
    const row = grid[r];
    for (let c = 0; c < row.length; c++) {
      const col = pal[row[c]];
      if (!col) continue;
      ctx.fillStyle = col;
      ctx.fillRect(x + c * scale, y + r * scale, scale, scale);
    }
  }
}

