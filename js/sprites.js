/* Fallback: a tinted blob colored by the Pokémon's primary type. */
const TYPE_COLOR = {
  normal: "N", fire: "O", water: "B", grass: "G", electric: "Y",
  poison: "P", flying: "S", bug: "g", ground: "n", rock: "S", psychic: "P",
};
function fallbackMon(species) {
  const t = (DEX[species] && DEX[species].types[0]) || "normal";
  const c = TYPE_COLOR[t] || "N";
  return [
    "....CCCC....".replace(/C/g, c),
    "..CCCCCCCC..".replace(/C/g, c),
    ".CCKCCCCKCC.".replace(/[C]/g, c),
    ".CCCCCCCCCC.".replace(/C/g, c),
    ".CCCWCCWCCC.".replace(/C/g, c),
    ".CCCCCCCCCC.".replace(/C/g, c),
    "..CCCCCCCC..".replace(/C/g, c),
    "...CC..CC...".replace(/C/g, c),
  ];
}
function monSprite(species) {
  return MON_SPRITES[species] || fallbackMon(species);
}

