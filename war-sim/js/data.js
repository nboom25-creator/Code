/* =============================================================================
 * data.js — the order of battle
 *
 * Every country is one record. Fields are grouped and use short keys so a whole
 * nation fits in a screenful. Any key you omit falls back to DEFAULTS, so a
 * record is never partially undefined downstream.
 *
 * UNITS  (read this before editing anything)
 * -----------------------------------------------------------------------------
 *  pop, fit, age .............. millions of people
 *  gdp, ppp, bud, budPpp ...... USD billions per year
 *  act, res, par .............. thousands of personnel
 *  tank..mlrs ................. vehicle/gun counts (units)
 *  ftr..uav ................... airframe counts (units)
 *  cv..pat .................... hull counts (units); ton = fleet displacement,
 *                               thousands of tonnes
 *  nuke, dep .................. warhead counts;  triad = legs held (0-3)
 *  brm, crm, hyp .............. 0-100 index of theatre-strike inventory + reach
 *  air ........................ usable airfields;  port = major seaports
 *  mm ......................... merchant vessels ≥1000 GT (sealift pool)
 *  rail, road ................. thousands of km
 *  oilp, oilc, ref ............ thousands of barrels/day
 *  steel ...................... million tonnes/year crude steel
 *  area ....................... thousands of km²;  coast = km
 *  terrain .................... 0-100 defensive difficulty of the ground
 *  tech..stab ................. 0-100 analyst indices (see README — these are
 *                               judgement calls, not measurements)
 *  bases ...................... permanent overseas military installations
 *
 * SOURCES
 * -----------------------------------------------------------------------------
 * Spending: SIPRI, "Trends in World Military Expenditure, 2025" (Apr 2026).
 * Order of battle: IISS Military Balance; Janes; national defence white papers.
 * Warheads: FAS Status of World Nuclear Forces (2026), ~12,187 global.
 * Economy/demography: IMF WEO, World Bank, UN WPP.
 * Infrastructure/energy: CIA World Factbook, EIA, World Steel Association.
 *
 * Counts are approximate and drift constantly; several states (North Korea,
 * Iran, Russia) publish nothing reliable. Treat every number as an estimate of
 * the right order of magnitude, not a fact.
 * ========================================================================== */

